"""
================================================================================
student/synthetic_dataset.py
================================================================================

Dataset and DataLoader utilities for the Student Model.
Loads the synthetic data generated by the Anchor model from Apache Arrow format.
"""

import json
from pathlib import Path
from typing import Tuple, Optional, List, Union
import torch
from torch.utils.data import Dataset, DataLoader
from .student_model import get_tokenizer

class SyntheticLMDataset(Dataset):
    """
    PyTorch Dataset wrapper for synthetic dataset records.
    Extracts text (from 'text' or 'generated_text'), tokenizes it, and creates attention_mask and labels.
    """
    def __init__(self, data_source, tokenizer, max_length: int = 1024, max_samples: Optional[int] = None):
        if hasattr(data_source, "select"):
            if max_samples is not None:
                self.dataset = data_source.select(range(min(max_samples, len(data_source))))
            else:
                self.dataset = data_source
        else:
            if max_samples is not None:
                self.dataset = list(data_source)[:max_samples]
            else:
                self.dataset = list(data_source)
        self.tokenizer = tokenizer
        self.max_length = max_length

    def __len__(self) -> int:
        return len(self.dataset)

    def __getitem__(self, idx: int) -> dict:
        item = self.dataset[idx]
        if isinstance(item, dict):
            text = item.get("text") or item.get("generated_text") or ""
        else:
            text = str(item)
        
        # Tokenize the text
        encodings = self.tokenizer(
            text,
            truncation=True,
            max_length=self.max_length,
            padding="max_length",
            return_tensors="pt"
        )
        
        input_ids = encodings["input_ids"].squeeze(0)
        attention_mask = encodings["attention_mask"].squeeze(0)
        
        return {
            "input_ids": input_ids,
            "attention_mask": attention_mask,
            "labels": input_ids.clone()
        }

def _load_jsonl_records(file_path: Path) -> List[dict]:
    """Loads records from a JSONL dataset file."""
    records = []
    with open(file_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line_str = line.strip()
            if line_str:
                records.append(json.loads(line_str))
    return records

def build_dataloaders(
    data_dir: Path,
    batch_size: int,
    val_ratio: float = 0.02,
    max_samples: Optional[int] = None,
    num_workers: int = 0
) -> Tuple[DataLoader, DataLoader]:
    """
    Load dataset from data_dir (JSONL files or Arrow directory), tokenize it, and split into loaders.
    """
    tokenizer = get_tokenizer()

    train_jsonl = data_dir / "train.jsonl"
    val_jsonl = data_dir / "validation.jsonl"

    if train_jsonl.exists():
        train_records = _load_jsonl_records(train_jsonl)
        if val_jsonl.exists():
            val_records = _load_jsonl_records(val_jsonl)
        else:
            n_total = len(train_records)
            n_val = max(1, int(n_total * val_ratio))
            n_train = n_total - n_val
            val_records = train_records[n_train:]
            train_records = train_records[:n_train]

        train_dataset = SyntheticLMDataset(train_records, tokenizer, max_samples=max_samples)
        val_dataset = SyntheticLMDataset(val_records, tokenizer, max_samples=max_samples)
    else:
        from datasets import load_from_disk
        hf_dataset = load_from_disk(str(data_dir))
        hf_dataset = hf_dataset.shuffle(seed=42)
        
        if max_samples:
            hf_dataset = hf_dataset.select(range(min(max_samples, len(hf_dataset))))
            
        n_total = len(hf_dataset)
        n_val = max(1, int(n_total * val_ratio))
        n_train = n_total - n_val
        
        train_dataset = SyntheticLMDataset(hf_dataset.select(range(n_train)), tokenizer)
        val_dataset = SyntheticLMDataset(hf_dataset.select(range(n_train, n_total)), tokenizer)

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
        drop_last=True if len(train_dataset) >= batch_size else False
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=torch.cuda.is_available(),
        drop_last=False
    )

    return train_loader, val_loader
